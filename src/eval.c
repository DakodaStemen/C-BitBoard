static const int PHASE_W[6] = { 0, 1, 1, 2, 4, 0 };   /* total = 24 */

int evaluate(const Position *pos) {
    int score[2] = { 0, 0 };
    int phase = 0;
    for (int c = 0; c < 2; c++) {
        for (int p = 0; p < 5; p++) {
            Bitboard b = pos->pieces[c][p];
            while (b) {
                int sq = bb_pop_lsb(&b);
                int idx = (c == WHITE) ? (sq ^ 56) : sq;
                score[c] += PIECE_VALUES[p] + PST[p][idx];
                phase += PHASE_W[p];
            }
        }
    }
    if (phase > 24) phase = 24;
    for (int c = 0; c < 2; c++) {
        int sq = bb_lsb(pos->pieces[c][KING]);
        int idx = (c == WHITE) ? (sq ^ 56) : sq;
        score[c] += (KING_MG[idx] * phase + KING_EG[idx] * (24 - phase)) / 24;
    }
    int s = score[WHITE] - score[BLACK];
    return (pos->side == WHITE ? s : -s) + 10;   /* small tempo bonus */
}
